const uint8_t kTransparentIndex = 0xff;


static inline uint32_t
ColorDistance(uint8_t red1, uint8_t green1, uint8_t blue1,
	uint8_t red2, uint8_t green2, uint8_t blue2)
{
	int rd = (int)red1 - (int)red2;
	int gd = (int)green1 - (int)green2;
	int bd = (int)blue1 - (int)blue2;
	int rmean = ((int)red1 + (int)red2) / 2;
	return (((512 + rmean) * rd * rd) >> 8) + 4 * gd * gd
		+ (((767 - rmean) * bd * bd) >> 8);
}


uint8_t
ClosestIndex(uint8_t red, uint8_t green, uint8_t blue)
{
	uint8_t closest = 0;
	uint32_t closestDistance = 0xffffffff;
	for (int32_t i = 0; i < 256; i++) {
		if (i == kTransparentIndex)
			continue;
		const IconRGB& color = kColors[i];
		uint32_t distance = ColorDistance(red, green, blue,
			color.r, color.g, color.b);
		if (distance < closestDistance) {
			closestDistance = distance;
			closest = (uint8_t)i;
		}
	}
	return closest;
}

